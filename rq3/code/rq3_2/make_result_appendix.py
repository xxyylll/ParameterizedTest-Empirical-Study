#!/usr/bin/env python3
"""
Generate the "complete results" appendix of each findings document directly
from the analysis output CSVs, so no number in the documents is hand-typed.

Each document gets everything between the markers

    <!-- APPENDIX:BEGIN ... -->
    <!-- APPENDIX:END -->

replaced (or the block appended if it is not there yet). Re-run this after
re-running any analysis to keep the documents in sync.

Convention inside the appendix: a Cliff's delta is shown in **bold** when it is
statistically significant (Holm-adjusted where the test is pairwise) AND at
least a small effect, |delta| >= 0.147 -- the same rule the figures use to
place a ***.
"""
# 向上找到 仓库根（paths.py 所在处）—— 不依赖本文件在目录树里的深度
import os as _os_root, sys as _sys_root
_root = _os_root.path.dirname(_os_root.path.abspath(__file__))
while not _os_root.path.exists(_os_root.path.join(_root, 'paths.py')):
    _root = _os_root.path.dirname(_root)
_sys_root.path.insert(0, _root)
import paths as _paths
import csv
import os

HERE = _paths.RQ3_2_RESULTS   # 读写 rq3/results/rq3_2/<子分析>/ 下的 CSV 与 FINDINGS 文档
SIG_P, SIG_DELTA = 0.05, 0.147

SCOPES = ['main-body', 'helper', 'total']
METRICS = ['LOC', 'CC', 'CCTR', 'DUP%', 'DUP lines']
ROWS = [(s, m) for s in SCOPES for m in METRICS]

BEGIN = '<!-- APPENDIX:BEGIN (generated by make_result_appendix.py -- do not edit by hand) -->'
END = '<!-- APPENDIX:END -->'


def read(path):
    with open(os.path.join(HERE, path), newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def fnum(s):
    try:
        return float(s)
    except (TypeError, ValueError):
        return None


def d_cell(delta, p):
    """Format a Cliff's delta, bolded when significant and at least small."""
    d, pv = fnum(delta), fnum(p)
    if d is None:
        return '—'
    txt = f'{d:.3f}'
    if pv is not None and pv < SIG_P and abs(d) >= SIG_DELTA:
        return f'**{txt}**'
    return txt


def label(scope, metric):
    return f'{metric} ({scope})'


def table(header, rows):
    out = ['| ' + ' | '.join(header) + ' |',
           '|' + '|'.join(['---'] * len(header)) + '|']
    out += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return '\n'.join(out)


def sep_rows(rows):
    """Insert a visual break between scope blocks."""
    out = []
    prev = None
    for scope, body in rows:
        if prev is not None and scope != prev:
            out.append(['', *[''] * (len(body) - 1)])
        out.append(body)
        prev = scope
    return out


# ---------------------------------------------------------------- RQ3.2
def rq32_appendix(prefix, title_n):
    constr = {(r['scope'], r['metric']): r for r in read(f'methodsource/{prefix}_construction_stats.csv')}
    kw = {(r['scope'], r['metric']): r for r in read(f'methodsource/{prefix}_dependency_kruskal.csv')}
    desc = {(r['scope'], r['metric'], r['dependency']): r
            for r in read(f'methodsource/{prefix}_dependency_descriptives.csv')}
    pair = {(r['scope'], r['metric'], r['comparison']): r
            for r in read(f'methodsource/{prefix}_dependency_pairwise.csv')}
    loo = {(r['comparison'], r['scope'], r['metric']): r
           for r in read(f'methodsource/{prefix}_robustness_loo.csv')}
    levels = ['L0', 'L1', 'L2', 'L3', 'L4']
    comps = [f'{b} vs {a}' for i, a in enumerate(levels) for b in levels[i + 1:]]

    parts = [f'## Appendix — complete results ({title_n})', '',
             'Every number below comes straight from the analysis CSVs via '
             '`make_result_appendix.py`. Bold = significant (Holm-adjusted for '
             'pairwise tests) and at least a small effect.', '',
             '### A1. Construction: Dynamic vs Literal', '',
             'Positive delta = Dynamic larger. The right-hand block repeats the '
             'contrast inside the L0 stratum, i.e. with dependency held fixed.', '']
    rows = []
    for scope, metric in ROWS:
        r = constr[(scope, metric)]
        rows.append((scope, [label(scope, metric), r['n_dynamic'], r['n_literal'],
                             r['median_dynamic'], r['median_literal'],
                             d_cell(r['cliffs_delta'], r['p_raw']), r['magnitude'],
                             r['p_raw'], r['p_bh_across_metrics'],
                             d_cell(r['L0_only_cliffs_delta'], r['L0_only_p_raw']),
                             r['L0_only_magnitude'], r['L0_only_p_raw']]))
    parts.append(table(['metric', 'n Dyn', 'n Lit', 'median Dyn', 'median Lit',
                        'delta', 'magnitude', 'p', 'p (BH)',
                        'delta L0-only', 'magnitude L0', 'p L0-only'], sep_rows(rows)))

    parts += ['', '### A2. Dependency: Kruskal–Wallis across L0–L4', '']
    rows = [(s, [label(s, m), kw[(s, m)]['n_total'], kw[(s, m)]['H'], kw[(s, m)]['df'],
                 kw[(s, m)]['p_raw'], kw[(s, m)]['p_bh_across_metrics'],
                 kw[(s, m)]['significant_005']]) for s, m in ROWS]
    parts.append(table(['metric', 'n', 'H', 'df', 'p', 'p (BH)', 'sig at .05'], sep_rows(rows)))

    parts += ['', '### A3. Dependency: medians by level', '']
    rows = [(s, [label(s, m)] + [f"{desc[(s, m, l)]['median']} (n={desc[(s, m, l)]['n']})"
                                  for l in levels]) for s, m in ROWS]
    parts.append(table(['metric'] + levels, sep_rows(rows)))

    parts += ['', '### A4. Dependency: pairwise Cliff\'s delta', '',
              'Positive delta = the higher level is larger.', '']
    rows = []
    for s, m in ROWS:
        cells = []
        for c in comps:
            r = pair.get((s, m, c))
            cells.append(d_cell(r['cliffs_delta'], r['p_holm']) if r else '—')
        rows.append((s, [label(s, m)] + cells))
    parts.append(table(['metric'] + comps, sep_rows(rows)))

    parts += ['', '### A5. Leave-one-project-out robustness', '',
              'Each headline delta recomputed with one project dropped at a time.', '']
    rows = []
    for comparison in ('Dynamic vs Literal', 'L4 vs L0'):
        for s, m in ROWS:
            r = loo.get((comparison, s, m))
            if r:
                rows.append((s, [comparison, label(s, m), r['delta_full'],
                                 f"{r['delta_min_loo']} .. {r['delta_max_loo']}",
                                 r['sign_stable']]))
    parts.append(table(['contrast', 'metric', 'delta (full)', 'delta range under LOO', 'sign stable'],
                       [r[1] for r in rows]))
    return '\n'.join(parts)


