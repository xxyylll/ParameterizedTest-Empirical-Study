def enum_appendix():
    two = {(r['contrast'], r['stratum'], r['scope'], r['metric']): r
           for r in read('enumsource/enumsource_twogroup_stats.csv')}
    desc = {(r['dimension'], r['group'], r['scope'], r['metric']): r
            for r in read('enumsource/enumsource_descriptives.csv')}
    kw = {(r['scope'], r['metric']): r for r in read('enumsource/enumsource_location_kruskal.csv')}
    dep = {(r['scope'], r['metric'], r['comparison']): r
           for r in read('enumsource/enumsource_dependency_pairwise.csv')}
    loo = {(r['contrast'], r['scope'], r['metric']): r
           for r in read('enumsource/enumsource_robustness_loo.csv')}
    conc = read('enumsource/enumsource_project_concentration.csv')

    parts = ['## Appendix — complete results', '',
             'Every number below comes straight from the analysis CSVs via '
             '`make_result_appendix.py`. Bold = significant and at least a small '
             'effect; note that for the location, names_mode and dependency '
             'contrasts significance does **not** imply the effect is '
             'attributable to the design dimension (see the concentration table '
             'in A6).', '',
             '### A1. enum_structure: Data-carrying vs Label-based', '',
             'Positive delta = Data-carrying larger. Right-hand columns repeat the '
             'contrast inside each enum_location stratum.', '']
    rows = []
    for s, m in ROWS:
        base = two[('structure', 'all', s, m)]
        prod = two.get(('structure', 'location_group=production', s, m))
        test = two.get(('structure', 'location_group=test', s, m))
        rows.append((s, [label(s, m), base['n_a'], base['n_b'], base['median_a'], base['median_b'],
                         d_cell(base['cliffs_delta'], base['p_raw']), base['magnitude'], base['p_raw'],
                         d_cell(prod['cliffs_delta'], prod['p_raw']) if prod else '—',
                         d_cell(test['cliffs_delta'], test['p_raw']) if test else '—']))
    parts.append(table(['metric', 'n DC', 'n LB', 'median DC', 'median LB', 'delta', 'magnitude',
                        'p', 'delta (production only)', 'delta (test only)'], sep_rows(rows)))

    parts += ['', '### A2. enum_location and names_mode contrasts', '',
              'Reported for completeness only — both fail the leave-one-project-out '
              'check (A5).', '']
    rows = []
    for s, m in ROWS:
        loc = two[('location', 'all', s, m)]
        nm = two[('names_mode', 'all', s, m)]
        rows.append((s, [label(s, m),
                         d_cell(loc['cliffs_delta'], loc['p_raw']), loc['magnitude'], loc['p_raw'],
                         d_cell(nm['cliffs_delta'], nm['p_raw']), nm['magnitude'], nm['p_raw']]))
    parts.append(table(['metric', 'delta test vs production', 'magnitude', 'p',
                        'delta SUBSET vs ALL', 'magnitude', 'p'], sep_rows(rows)))

    parts += ['', '### A3. Kruskal–Wallis across the four enum_location groups', '']
    rows = [(s, [label(s, m), kw[(s, m)]['n_total'], kw[(s, m)]['H'], kw[(s, m)]['df'],
                 kw[(s, m)]['p_raw'], kw[(s, m)]['p_bh'], kw[(s, m)]['significant_005']])
            for s, m in ROWS]
    parts.append(table(['metric', 'n', 'H', 'df', 'p', 'p (BH)', 'sig at .05'], sep_rows(rows)))

    parts += ['', '### A4. dependency inside test-scope enums (L1 / L3 / L4)', '',
              'Computed and reported in full, but **not interpretable as a '
              'dependency effect** — L3 is 99% jena, so these contrasts are '
              'largely project contrasts (see A6 and the discussion above). '
              'Positive delta = the higher level larger.', '']
    comps = ['L3 vs L1', 'L4 vs L1', 'L4 vs L3']
    rows = []
    for s, m in ROWS:
        cells = []
        for c in comps:
            r = dep.get((s, m, c))
            cells.append(d_cell(r['cliffs_delta'], r['p_holm']) if r else '—')
        kwp = dep.get((s, m, comps[0]))
        rows.append((s, [label(s, m)] + cells + [kwp['kw_p'] if kwp else '—']))
    parts.append(table(['metric'] + comps + ['KW p'], sep_rows(rows)))

    parts += ['', '### A5. Leave-one-project-out robustness', '']
    rows = []
    for contrast in ('Data-carrying vs Label-based', 'test vs production', 'SUBSET vs ALL'):
        for s, m in ROWS:
            r = loo.get((contrast, s, m))
            if r:
                rows.append([contrast, label(s, m), r['delta_full'],
                             f"{r['delta_min_loo']} .. {r['delta_max_loo']}", r['sign_stable']])
    parts.append(table(['contrast', 'metric', 'delta (full)', 'delta range under LOO', 'sign stable'], rows))

    parts += ['', '### A6. Project concentration per group', '',
              'Why A2 and A4 are not reported as findings.', '']
    rows = [[r['dimension'], r['group'], r['n'], r['projects'], r['top_project'],
             f"{float(r['top_project_share']):.0%}"] for r in conc]
    parts.append(table(['dimension', 'group', 'n', 'projects', 'largest project', 'its share'], rows))
    return '\n'.join(parts)


