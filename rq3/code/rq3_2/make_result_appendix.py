def rq33_appendix():
    SOURCES = ['ValueSource', 'CsvSource', 'EnumSource', 'CsvFileSource',
               'MethodSource', 'ArgumentsSource', 'FieldSource']
    FAMILIES = ['inline', 'type', 'file', 'provider']
    desc = {(r['scope'], r['metric'], r['group']): r for r in read('cross_source/cross_source_descriptives.csv')}
    kw = {(r['scope'], r['metric']): r for r in read('cross_source/cross_source_kruskal.csv')}
    pair = {(r['scope'], r['metric'], r['comparison']): r for r in read('cross_source/cross_source_pairwise.csv')}
    fam = {(r['scope'], r['metric'], r['comparison']): r for r in read('cross_source/cross_source_family_pairwise.csv')}
    vol = {(r['scope'], r['metric'], r['stratum']): r for r in read('cross_source/cross_source_volume_strata.csv')}
    loo = {(r['scope'], r['metric']): r for r in read('cross_source/cross_source_robustness_loo.csv')}
    fam_comps = [f'{b} vs {a}' for i, a in enumerate(FAMILIES) for b in FAMILIES[i + 1:]]
    strata = ['Q1', 'Q2', 'Q3', 'Q4']

    parts = ['## Appendix — complete results', '',
             'Every number below comes straight from the analysis CSVs via '
             '`make_result_appendix.py`. Bold = significant (Holm-adjusted for '
             'pairwise tests) and at least a small effect.', '',
             '### A1. Medians by source type', '']
    rows = [(s, [label(s, m)] + [f"{desc[(s, m, src)]['median']}" for src in SOURCES]) for s, m in ROWS]
    parts.append(table(['metric'] + [s.replace('Source', '') for s in SOURCES], sep_rows(rows)))
    parts.append('')
    parts.append('n per source: ' + ', '.join(
        f"{s}={desc[('total', 'LOC', s)]['n']}" for s in SOURCES) + '.')

    parts += ['', '### A2. Kruskal–Wallis across source types and across families', '']
    rows = [(s, [label(s, m), kw[(s, m)]['H_source'], kw[(s, m)]['p_source'],
                 kw[(s, m)]['p_source_bh'], kw[(s, m)]['H_family'], kw[(s, m)]['p_family']])
            for s, m in ROWS]
    parts.append(table(['metric', 'H (source, df=6)', 'p', 'p (BH)', 'H (family, df=3)', 'p'], sep_rows(rows)))

    parts += ['', '### A3. Each source vs the ValueSource baseline', '',
              'Positive delta = that source larger than ValueSource.', '']
    others = [s for s in SOURCES if s != 'ValueSource']
    rows = []
    for s, m in ROWS:
        cells = []
        for src in others:
            r = pair.get((s, m, f'{src} vs ValueSource'))
            cells.append(d_cell(r['cliffs_delta'], r['p_holm']) if r else '—')
        rows.append((s, [label(s, m)] + cells))
    parts.append(table(['metric'] + [o.replace('Source', '') for o in others], sep_rows(rows)))

    parts += ['', '### A4. Mechanism families, all pairs', '',
              'Positive delta = the second-named family larger.', '']
    rows = []
    for s, m in ROWS:
        cells = []
        for c in fam_comps:
            r = fam.get((s, m, c))
            cells.append(d_cell(r['cliffs_delta'], r['p_holm']) if r else '—')
        rows.append((s, [label(s, m)] + cells))
    parts.append(table(['metric'] + fam_comps, sep_rows(rows)))

    parts += ['', '### A5. Provider vs inline inside n_sets quartiles', '',
              'Data-volume control. Positive delta = provider larger.', '']
    rows = []
    for s, m in ROWS:
        cells = []
        for q in strata:
            r = vol.get((s, m, q))
            cells.append(d_cell(r['cliffs_delta'], r['p_raw']) if r else '—')
        rows.append((s, [label(s, m)] + cells))
    hdr = [f"{q} (n_sets {vol[('total', 'LOC', q)]['n_sets_range']})" for q in strata]
    parts.append(table(['metric'] + hdr, sep_rows(rows)))

    parts += ['', '### A6. Leave-one-project-out robustness (provider vs inline)', '']
    rows = []
    for s, m in ROWS:
        r = loo.get((s, m))
