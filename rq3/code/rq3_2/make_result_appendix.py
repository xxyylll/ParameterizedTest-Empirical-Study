def amort_appendix():
    dist = read('amortization/amortization_distributions.csv')
    comp = read('amortization/amortization_model_comparison.csv')
    prof = read('amortization/amortization_profile.csv')
    val = read('amortization/amortization_reuse_dup_validity.csv')
    loo = read('amortization/amortization_robustness_loo.csv')

    GROUPS = [('category', ['nonpt', 'pt']),
              ('dependency', ['L0', 'L1', 'L2', 'L3', 'L4']),
              ('family', ['inline', 'type', 'file', 'provider']),
              ('construction', ['Literal', 'Dynamic'])]

    parts = ['## Appendix — complete results', '',
             'Generated from the analysis CSVs by `make_result_appendix.py`; no '
             'number here is hand-typed. Bold = significant and at least a small '
             'effect.', '',
             '### A1. Full distribution of complexity-weighted helper reuse', '',
             'The central tendency alone is misleading here: these distributions are '
             'strongly right-skewed and heavy-tailed, with the mean several times the '
             'median. `share = 1` is the fraction of tests whose helper complexity is '
             'shared with no other test at all.', '']
    idx = {(r['dimension'], r['group'], r['metric']): r for r in dist}
    rows = []
    for dim, groups in GROUPS:
        for g in groups:
            r = idx.get((dim, g, 'amortization_cctr'))
            if not r:
                continue
            rows.append([f'{dim}={g}', r['n'], r['mean'], r['sd'], r['cv'],
                         r['min'], r['p5'], r['q1'], r['median'], r['q3'],
                         r['p90'], r['p95'], r['p99'], r['max'],
                         r['share_eq_1'], r['share_le_2'], r['share_ge_100']])
    parts.append(table(['group', 'n', 'mean', 'SD', 'CV', 'min', 'p5', 'q1', 'median',
                        'q3', 'p90', 'p95', 'p99', 'max',
                        'share =1', 'share <=2', 'share >=100'], rows))

    parts += ['', '### A2. Full distribution of the other amortisation measures', '']
    for metric, label in [('private_cctr_share', 'private CCTR share'),
                          ('helper_count', 'helper count'),
                          ('single_use_helper_count', 'single-use helper count'),
                          ('maintainer_total_cctr', 'maintainer total CCTR'),
                          ('reader_total_cctr', 'reader total CCTR')]:
        rows = []
        for dim, groups in GROUPS:
            for g in groups:
                r = idx.get((dim, g, metric))
                if not r:
                    continue
                rows.append([f'{dim}={g}', r['n'], r['mean'], r['sd'], r['min'],
                             r['q1'], r['median'], r['q3'], r['p90'], r['p99'], r['max']])
        parts += [f'**{label}**', '']
        parts.append(table(['group', 'n', 'mean', 'SD', 'min', 'q1', 'median', 'q3',
                            'p90', 'p99', 'max'], rows))
        parts.append('')

    parts += ['### A3. Both accounting models, every contrast and measure', '',
              'Positive delta = the first-named group larger.', '']
    contrasts = []
    for r in comp:
        if r['contrast'] not in contrasts:
            contrasts.append(r['contrast'])
    cidx = {(r['contrast'], r['measure']): r for r in comp}
    rows = []
    for c in contrasts:
        for m in ('LOC', 'CC', 'CCTR'):
            r = cidx.get((c, m))
            if not r:
                continue
            rows.append([c, m, r['n_a'], r['n_b'],
                         d_cell(r['delta_reader'], r['p_reader']), r['magnitude_reader'],
                         d_cell(r['delta_maintainer'], r['p_maintainer']), r['magnitude_maintainer'],
                         r['delta_shrinks'], r['crosses_to_negligible']])
    parts.append(table(['contrast', 'measure', 'n (a)', 'n (b)', 'delta reader', 'magnitude',
                        'delta maintainer', 'magnitude', 'gap shrinks', 'to negligible'], rows))

    parts += ['', '### A4. Amortisation and private share, by contrast (CCTR)', '']
    rows = []
    for c in contrasts:
        r = cidx.get((c, 'CCTR'))
        if not r:
            continue
        rows.append([c, d_cell(r['delta_amortization'], r['p_amortization']),
                     r['magnitude_amortization'], r['p_amortization'],
                     d_cell(r['delta_private_share'], r['p_private_share']),
                     r['magnitude_private_share'], r['p_private_share']])
    parts.append(table(['contrast', 'delta weighted reuse', 'magnitude', 'p',
                        'delta private share', 'magnitude', 'p'], rows))

    parts += ['', '### A5. Per-group amortisation profile', '']
    rows = [[r['dimension'] + '=' + r['group'], r['n'], r['median_helper_count'],
             r['median_single_use_helpers'], r['amortization_cctr_median'],
             r['amortization_cctr_mean'], r['private_cctr_share_median'],
             r['private_cctr_share_mean'], r['n_with_defined_ratio']] for r in prof]
    parts.append(table(['group', 'n', 'median helpers', 'median single-use helpers',
                        'weighted reuse (median)', 'weighted reuse (mean)',
                        'private share (median)', 'private share (mean)',
                        'n with defined ratio'], rows))

    parts += ['', '### A6. Reuse vs duplication — convergent validity', '',
              'DUP is deliberately not amortised; it is used to validate the reuse '
              'measure against an independent tool (CCFinderSW).', '']
    rows = [[r['x'], r['y'], r['n'], r['spearman_rho'], r['p_raw']]
            for r in val if r['spearman_rho']]
    parts.append(table(['x', 'y', 'n', "Spearman rho", 'p'], rows))
    parts += ['', 'Binned view — median helper duplication by reuse decile:', '']
    rows = [[r['x'], r['n'], r['scope']] for r in val if not r['spearman_rho']]
    parts.append(table(['decile', 'n', 'weighted reuse range -> median helper DUP%'], rows))

    parts += ['', '### A7. Leave-one-project-out robustness', '']
    rows = [[r['contrast'], r['metric'], r['delta_full'],
             f"{r['delta_min_loo']} .. {r['delta_max_loo']}", r['n_projects'], r['sign_stable']]
            for r in loo]
    parts.append(table(['contrast', 'metric', 'delta (full)', 'delta range under LOO',
                        'projects', 'sign stable'], rows))
    return '\n'.join(parts)


def splice(path, body):
    full = os.path.join(HERE, path)
    s = open(full).read()
    block = f'{BEGIN}\n\n{body}\n\n{END}'
    if BEGIN in s and END in s:
        pre = s[:s.index(BEGIN)]
        post = s[s.index(END) + len(END):]
        s = pre + block + post
    else:
        s = s.rstrip() + '\n\n---\n\n' + block + '\n'
    open(full, 'w').write(s)
    print(f'appendix written -> {path} ({len(body.splitlines())} lines)')


